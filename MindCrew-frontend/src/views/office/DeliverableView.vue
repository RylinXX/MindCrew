<script setup lang="ts">
import { computed, onMounted, reactive, ref } from 'vue'
import { ElMessage } from 'element-plus'
import { Download } from '@element-plus/icons-vue'
import { officeApi, type ContractTemplate } from '@/api/office'
import { downloadBlob } from '@/utils/download'

const activeTab = ref('ppt')
const generating = ref<'' | 'ppt' | 'word' | 'contract'>('')

// ─────────────────────────────────────────────
// PPT
// ─────────────────────────────────────────────
const ppt = reactive({
  title: '',
  subtitle: '',
  markdown: `## 背景与目标

- 用 Agentic RAG 统一知识检索与问答
- 覆盖客服、调研、教练等业务场景

## 关键进展

- 知识库接入 12 个部门
- 平均响应时间下降 38%
- 客服人工转接率降至 18%

## 下一步计划

- 扩大检索分析覆盖面
- 完善多智能体交付物
`
})

const pptSections = computed(() => {
  const result: Array<{ title: string; bullets: number }> = []
  let current: { title: string; bullets: number } | null = null
  for (const raw of ppt.markdown.split('\n')) {
    const line = raw.trim()
    if (!line) continue
    if (line.startsWith('## ')) {
      current = { title: line.slice(3).trim(), bullets: 0 }
      result.push(current)
    } else if (line.startsWith('# ')) {
      continue
    } else if (current) {
      current.bullets += 1
    }
  }
  return result
})

const pptPages = computed(() => {
  if (!ppt.markdown.trim()) return 0
  let pages = 1 // 封面
  const sections = pptSections.value
  if (sections.length) pages += 1 // 目录
  if (!sections.length) {
    const paragraphs = ppt.markdown.split(/\n+/).filter(Boolean).length
    return pages + Math.max(1, Math.ceil(paragraphs / 6))
  }
  for (const section of sections) {
    pages += Math.max(1, Math.ceil(section.bullets / 6))
  }
  return pages
})

// ─────────────────────────────────────────────
// Word
// ─────────────────────────────────────────────
const word = reactive({
  title: '',
  markdown: `## 一、概述

本文说明知识库权限配置方式，帮助管理员快速完成部门与职位范围设置。

## 二、配置步骤

1. 进入「知识库」页面
2. 选择目标文档并设置可见性
3. 在「组织与职位」中分配范围

## 三、注意事项

- 公开文档对所有登录用户可见
- 私有文档仅创建者可见
`
})

const wordChars = computed(() => word.markdown.replace(/\s/g, '').length)

const wordPreviewLines = computed(() => {
  const lines: Array<{ type: 'h1' | 'h2' | 'p'; text: string }> = []
  for (const raw of word.markdown.split('\n')) {
    const line = raw.trim()
    if (!line) continue
    if (line.startsWith('## ')) lines.push({ type: 'h1', text: line.slice(3) })
    else if (line.startsWith('### ')) lines.push({ type: 'h2', text: line.slice(4) })
    else if (line.startsWith('# ')) lines.push({ type: 'h1', text: line.slice(2) })
    else lines.push({ type: 'p', text: line })
  }
  return lines.slice(0, 40)
})

// ─────────────────────────────────────────────
// 合同
// ─────────────────────────────────────────────
const templates = ref<ContractTemplate[]>([])
const contract = reactive({ template: '' })
const contractFields = reactive<Record<string, string>>({})

const currentTemplate = computed(() => templates.value.find(tpl => tpl.id === contract.template) || null)

const today = computed(() => {
  const now = new Date()
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
})

function addDays(days: number): string {
  const date = new Date()
  date.setDate(date.getDate() + days)
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
}

function fieldPlaceholder(field: { key: string; label: string }): string {
  if (field.key === 'amount') return '如：100000（自动转中文大写）'
  if (field.key === 'signDate') return '如：2026-11-10'
  if (field.key === 'deliveryDate') return '如：2026-12-01'
  if (field.key === 'servicePeriod') return '如：2026-11-01 至 2026-12-31'
  return `请输入${field.label}`
}

function onTemplateChange() {
  const tpl = currentTemplate.value
  for (const key of Object.keys(contractFields)) delete contractFields[key]
  if (!tpl) return
  for (const field of tpl.fields) {
    if (field.key === 'signDate') contractFields[field.key] = today.value
    else if (field.key === 'deliveryDate') contractFields[field.key] = addDays(21)
    else contractFields[field.key] = ''
  }
}

async function loadTemplates() {
  try {
    templates.value = await officeApi.listTemplates()
    const first = templates.value[0]
    if (first) {
      contract.template = first.id
      onTemplateChange()
    }
  } catch (e: any) {
    ElMessage.error('加载合同模板失败：' + (e?.message || ''))
  }
}

// ─────────────────────────────────────────────
// 生成
// ─────────────────────────────────────────────
async function generatePpt() {
  if (!ppt.title.trim()) return ElMessage.warning('请填写 PPT 标题')
  if (!ppt.markdown.trim()) return ElMessage.warning('请填写 Markdown 正文')
  generating.value = 'ppt'
  try {
    const file = await officeApi.generatePptx({
      title: ppt.title.trim(),
      subtitle: ppt.subtitle.trim() || undefined,
      markdown: ppt.markdown
    })
    downloadBlob(file.blob, file.filename || `${ppt.title.trim()}.pptx`)
    ElMessage.success('PPT 已生成')
  } catch (e: any) {
    ElMessage.error('生成失败：' + (e?.message || ''))
  } finally {
    generating.value = ''
  }
}

async function generateWord() {
  if (!word.title.trim()) return ElMessage.warning('请填写文档标题')
  if (!word.markdown.trim()) return ElMessage.warning('请填写 Markdown 正文')
  generating.value = 'word'
  try {
    const file = await officeApi.generateDocx({
      title: word.title.trim(),
      markdown: word.markdown
    })
    downloadBlob(file.blob, file.filename || `${word.title.trim()}.docx`)
    ElMessage.success('Word 已生成')
  } catch (e: any) {
    ElMessage.error('生成失败：' + (e?.message || ''))
  } finally {
    generating.value = ''
  }
}

async function generateContract() {
  if (!contract.template) return ElMessage.warning('请选择合同模板')
  const tpl = currentTemplate.value
  if (tpl) {
    const missing = tpl.fields.filter(field => field.required && !String(contractFields[field.key] ?? '').trim())
    if (missing.length) return ElMessage.warning(`请填写：${missing.map(f => f.label).join('、')}`)
  }
  generating.value = 'contract'
  try {
    const file = await officeApi.generateContract({
      template: contract.template,
      fields: { ...contractFields }
    })
    downloadBlob(file.blob, file.filename || `${tpl?.name || '合同'}.docx`)
    ElMessage.success('合同已生成')
  } catch (e: any) {
    ElMessage.error('生成失败：' + (e?.message || ''))
  } finally {
    generating.value = ''
  }
}

onMounted(loadTemplates)
</script>

